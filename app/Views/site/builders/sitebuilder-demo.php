  var colors = <?= json_encode($aoBuilderColors, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) ?>;
  var preview = document.querySelector('[data-sitebuilder-demo-preview]');
  if (!preview) return;

  function text(selector, value) {
    var node = preview.querySelector(selector);
    if (node) node.textContent = value || '';
  }

  function selectedTemplate() {
    var select = document.querySelector('#template') || document.querySelector('[data-sitebuilder-template-select]');
    return select ? (select.value || 'hosting') : 'hosting';
  }

  function normalizeHex(value) {
    value = String(value || '').trim();
    if (value.charAt(0) !== '#') value = '#' + value;
    return /^#[0-9a-f]{6}$/i.test(value) ? value.toUpperCase() : '';
  }

  function tint(hex, amount) {
    hex = normalizeHex(hex) || '#3B82F6';
    var num = parseInt(hex.slice(1), 16);
    var r = Math.min(255, Math.max(0, (num >> 16) + amount));
    var g = Math.min(255, Math.max(0, ((num >> 8) & 255) + amount));
    var b = Math.min(255, Math.max(0, (num & 255) + amount));
    return '#' + [r, g, b].map(function(v){ return v.toString(16).padStart(2, '0'); }).join('').toUpperCase();
  }

  function selectedColor() {
    var select = document.querySelector('#color') || document.querySelector('[data-builder-color-select]');
    var picker = document.querySelector('#color') ? document.querySelector('#color').closest('.builder-color-control').querySelector('[data-builder-color-picker]') : document.querySelector('[data-builder-color-picker]');
    var key = select ? select.value : 'blue';
    return key === 'custom' ? (normalizeHex(picker && picker.value) || '#3B82F6') : (colors[key] || '#3B82F6');
  }

  function syncColors(hex, source) {
    document.querySelectorAll('[data-builder-color-picker]').forEach(function(input){ if (input !== source) input.value = hex; });
    document.querySelectorAll('[data-builder-color-code]').forEach(function(input){ if (input !== source) input.value = hex; });
  }

  function applyColor(hex) {
    hex = normalizeHex(hex) || '#3B82F6';
    preview.style.setProperty('--builder-accent', hex);
    preview.style.setProperty('--builder-accent-soft', tint(hex, 34));
    preview.style.setProperty('--builder-accent-wash', tint(hex, 178));
    preview.style.setProperty('--builder-accent-border', tint(hex, 136));
    syncColors(hex, null);
  }

  function syncSelects(value) {
    document.querySelectorAll('[data-sitebuilder-template-select]').forEach(function(select){
      if (select.value !== value && templates[value]) select.value = value;
    });
  }

  function overrideValue(name) {
    var field = document.querySelector('[data-preview-field="' + name + '"]');
    if (field && (field.disabled || field.closest('[hidden]'))) return '';
    return field ? field.value.trim() : '';
  }

  function menuLabels(fallback) {
    var raw = overrideValue('menu');
    if (!raw) return fallback || [];
    return raw.split(',').map(function(item){ return item.trim(); }).filter(Boolean).slice(0, 3);
  }

  function listValue(name, fallback, limit) {
    var raw = overrideValue(name);
    var values = raw ? raw.split(',').map(function(item){ return item.trim(); }).filter(Boolean) : (fallback || []);
    return values.slice(0, limit || 3);
  }

  function templateKind(value) {
    if (value === 'radio') return 'radio';
    if (['ecommerce', 'restaurant', 'software'].indexOf(value) !== -1) return 'commerce';
    if (['realestate', 'landing', 'corporate', 'agency', 'news'].indexOf(value) !== -1) return 'service';
    return 'general';
  }

  function scopeAllowed(scope, kind) {
    if (!scope) return true;
    var scopes = scope.split(/\s+/).filter(Boolean);
    return scopes.indexOf(kind) !== -1;
  }

  function applyTemplateScopes(value) {
    var kind = templateKind(value);
    document.querySelectorAll('[data-template-scope]').forEach(function(node){
      var show = scopeAllowed(node.dataset.templateScope || '', kind);
      node.hidden = !show;
      node.querySelectorAll('input,select,textarea,button').forEach(function(control){
        if (control.matches('[data-preview-toggle], [data-preview-device]')) return;
        control.disabled = !show;
      });
    });
    preview.classList.toggle('is-radio-template', kind === 'radio');
    preview.classList.toggle('is-commerce-template', kind === 'commerce');
    preview.classList.toggle('is-service-template', kind === 'service');
    var playerToggle = document.querySelector('[data-preview-toggle="player"]');
    var player = preview.querySelector('[data-preview-player]');
    if (kind !== 'radio') {
      if (playerToggle) playerToggle.checked = false;
      if (player) player.hidden = true;
    }
  }

  function render(value) {
    var item = templates[value] || templates.hosting;
    if (!item) return;
    preview.dataset.design = item.design || 'tech-dark';
    syncSelects(value);
    applyTemplateScopes(value);
    text('[data-preview-brand]', item.brand || 'Logo');
    text('[data-preview-tag]', item.tag || '');
    text('[data-preview-title]', overrideValue('title') || item.title || '');
    text('[data-preview-desc]', overrideValue('desc') || item.desc || '');
    text('[data-preview-button]', overrideValue('button') || item.button || 'Başla');
    text('[data-preview-button-secondary]', overrideValue('button_secondary') || 'Detayları Gör');
    text('[data-preview-metric]', item.metric || '');
    text('[data-preview-metric-label]', item.metricLabel || '');
    menuLabels(item.nav || []).forEach(function(label, index){ text('[data-preview-nav="' + index + '"]', label); });
    listValue('slider', ['Hızlı Kurulum', 'Kampanya Alanı', 'Canlı Destek'], 3).forEach(function(label, index){ text('[data-preview-slider="' + index + '"]', label); });
    text('[data-preview-person]', overrideValue('person') || (value === 'radio' ? 'Canlı yayın ekibi' : 'Profesyonel ekip'));
    text('[data-preview-time]', overrideValue('time') || (value === 'radio' ? 'Her gün 20:00 - 24:00' : 'Hafta içi 09:00 - 18:00'));
    text('[data-preview-campaign]', overrideValue('campaign') || (value === 'radio' ? 'Yeni program akışı yayında' : 'Yeni fırsatlar yayında'));
    text('[data-preview-social]', overrideValue('social') || (value === 'radio' ? 'WhatsApp, Instagram, YouTube' : 'Form, WhatsApp, Telefon'));
    listValue('flow', item.flow || [], 4).forEach(function(label, index){ text('[data-preview-flow="' + index + '"]', label); });
    listValue('payments', item.payments || [], 4).forEach(function(label, index){ text('[data-preview-payment="' + index + '"]', label); });
    var kind = templateKind(value);
    var flow = preview.querySelector('.preview-flow');
    var payments = preview.querySelector('.preview-payments');
    if (flow) flow.hidden = !(item.flow && item.flow.length);
    if (payments) payments.hidden = !(item.payments && item.payments.length);
    text('[data-preview-player-title]', overrideValue('player') || (value === 'radio' ? 'Ahost Radio Canlı Yayın' : 'Canlı içerik player'));
    var player = preview.querySelector('[data-preview-player]');
    var playerToggle = document.querySelector('[data-preview-toggle="player"]');
    if (player && playerToggle && value === 'radio' && !playerToggle.checked && !overrideValue('player')) playerToggle.checked = true;
    if (player && playerToggle) player.hidden = kind !== 'radio' || !playerToggle.checked;
    listValue('cards', item.cards || [], 3).forEach(function(label, index){ text('[data-preview-card="' + index + '"]', label); });
    applyColor(selectedColor());
  }

  function selectedAddonValues() {
    return Array.prototype.slice.call(document.querySelectorAll('[data-builder-selected-modules] [data-builder-addon-value]'))
      .map(function(input){ return input.value; })
      .filter(Boolean);
  }

  function addSelectedAddon() {
    var select = document.querySelector('[data-builder-addon-select]');
    var list = document.querySelector('[data-builder-selected-modules]');
    if (!select || !list || !select.value) return;
    if (selectedAddonValues().indexOf(select.value) !== -1) {
      select.value = '';
      return;
    }
    var option = select.options[select.selectedIndex];
    var item = document.createElement('span');
    item.className = 'builder-module-chip';
    item.innerHTML = '<input type="hidden" data-builder-addon-value value=""> <b></b><button type="button" aria-label="Modülü kaldır" data-builder-addon-remove>×</button>';
    item.querySelector('input').value = select.value;
    item.querySelector('b').textContent = option ? option.textContent.trim() : select.value;
    list.appendChild(item);
    select.value = '';
  }

  function fieldByPreviewName(name) {
    return document.querySelector('[data-preview-field="' + name + '"]');
  }

  function focusBuilderField(name) {
    var field = fieldByPreviewName(name);
    if (!field) return null;
    field.scrollIntoView({behavior: 'smooth', block: 'center'});
    field.focus({preventScroll: true});
    return field;
  }

  function appendCsvValue(field, value) {
    if (!field || !value) return;
    var current = field.value.split(',').map(function(item){ return item.trim(); }).filter(Boolean);
    if (current.indexOf(value) === -1) current.push(value);
    field.value = current.join(', ');
    field.dispatchEvent(new Event('input', {bubbles: true}));
  }

  function runBuilderTool(tool) {
    var field;
    if (tool === 'frontend' || tool === 'text-edit') {
      focusBuilderField('title');
      return;
    }
    if (tool === 'slider-add' || tool === 'slider-edit') {
      field = focusBuilderField('slider');
      if (tool === 'slider-add') appendCsvValue(field, 'Yeni Slider');
      return;
    }
    if (tool === 'menu-add' || tool === 'menu-edit') {
      field = focusBuilderField('menu');
      if (tool === 'menu-add') appendCsvValue(field, 'Yeni Menü');
      return;
    }
    if (tool === 'page-add' || tool === 'page-edit') {
      field = focusBuilderField('pages');
      if (tool === 'page-add') appendCsvValue(field, 'Yeni Sayfa');
      return;
    }
    if (tool === 'block-up' || tool === 'block-down') {
      field = focusBuilderField('block_order');
      if (field && !field.value.trim()) {
        field.value = 'Hero, Slider, Hizmetler, Ödeme, İletişim';
        field.dispatchEvent(new Event('input', {bubbles: true}));
      }
    }
  }

  document.addEventListener('change', function(event){
    var select = event.target.closest('[data-sitebuilder-template-select]');
    if (!select) return;
    render(select.value);
  });

  document.addEventListener('input', function(event){
    if (event.target && (event.target.id === 'sitename' || event.target.id === 'ai_sitename')) {
      var item = templates[selectedTemplate()] || templates.hosting;
      text('[data-preview-brand]', event.target.value.trim() || (item ? item.brand : 'Logo'));
    }
    if (event.target && event.target.matches('[data-preview-field]')) {
      render(selectedTemplate());
    }
    if (event.target && event.target.matches('[data-builder-color-picker],[data-builder-color-code]')) {
      var hex = normalizeHex(event.target.value);
      if (!hex) return;
      var wrap = event.target.closest('.builder-color-control');
      if (wrap) {
        var select = wrap.querySelector('[data-builder-color-select]');
        if (select) select.value = 'custom';
      }
      applyColor(hex);
    }
  });

  document.addEventListener('click', function(event){
    var addAddon = event.target.closest('[data-builder-addon-add]');
    if (addAddon) {
      addSelectedAddon();
      return;
    }
    var removeAddon = event.target.closest('[data-builder-addon-remove]');
    if (removeAddon) {
      var chip = removeAddon.closest('.builder-module-chip');
      if (chip) chip.remove();
      return;
    }
    var tool = event.target.closest('[data-builder-tool]');
    if (tool) {
      runBuilderTool(tool.dataset.builderTool || '');
      return;
    }
    var device = event.target.closest('[data-preview-device]');
    if (!device) return;
    document.querySelectorAll('[data-preview-device]').forEach(function(button){ button.classList.remove('active'); });
    device.classList.add('active');
    preview.classList.toggle('is-mobile-preview', device.dataset.previewDevice === 'mobile');
  });

  document.addEventListener('change', function(event){
    var toggle = event.target.closest('[data-preview-toggle]');
    if (!toggle) return;
    if (toggle.dataset.previewToggle === 'whatsapp') {
      var whatsapp = preview.querySelector('[data-preview-whatsapp]');
      if (whatsapp) whatsapp.hidden = !toggle.checked;
    }
    if (toggle.dataset.previewToggle === 'search') {
      var search = preview.querySelector('[data-preview-search]');
      if (search) search.hidden = !toggle.checked;
    }
    if (toggle.dataset.previewToggle === 'player') {
      var player = preview.querySelector('[data-preview-player]');
      if (player) player.hidden = !toggle.checked;
    }
  });

  render(selectedTemplate());
  document.addEventListener('change', function(event){
    var colorSelect = event.target.closest('[data-builder-color-select]');
    if (!colorSelect) return;
    var hex = colorSelect.value === 'custom'
      ? normalizeHex(colorSelect.closest('.builder-color-control').querySelector('[data-builder-color-picker]').value)
      : colors[colorSelect.value];
    applyColor(hex || '#3B82F6');
  });

  document.addEventListener('submit', function(event){
    var form = event.target.closest('[data-builder-package-form]');
    if (!form) return;
    form.querySelectorAll('[data-builder-generated]').forEach(function(input){ input.remove(); });
    var fields = {
      template: selectedTemplate(),
      sitename: (document.querySelector('#sitename') || {}).value || (document.querySelector('#ai_sitename') || {}).value || '',
      color: (document.querySelector('#color') || {}).value || 'blue',
      custom_color: selectedColor(),
      menu: overrideValue('menu'),
      pages: overrideValue('pages'),
      block_order: overrideValue('block_order'),
      title: overrideValue('title'),
      description: overrideValue('desc'),
      cta: overrideValue('button'),
      cta_secondary: overrideValue('button_secondary'),
      slider: overrideValue('slider'),
      cards: overrideValue('cards'),
      live_person: overrideValue('person'),
      live_time: overrideValue('time'),
      player_title: overrideValue('player'),
      campaign: overrideValue('campaign'),
      social: overrideValue('social'),
      flow: overrideValue('flow'),
      payments: overrideValue('payments')
    };
    Object.keys(fields).forEach(function(name){
      var input = document.createElement('input');
      input.type = 'hidden';
      input.name = name;
      input.value = fields[name] || '';
      input.setAttribute('data-builder-generated', '1');
      form.appendChild(input);
    });
    selectedAddonValues().forEach(function(value){
      var input = document.createElement('input');
      input.type = 'hidden';
      input.name = 'builder_addons[]';
      input.value = value;
      input.setAttribute('data-builder-generated', '1');
      form.appendChild(input);
    });
  });
})();
</script>
